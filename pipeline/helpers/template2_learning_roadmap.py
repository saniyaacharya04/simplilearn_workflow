"""
template2_learning_roadmap.py — Simplilearn OSL 3.0 Learning Roadmap Template
=============================================================================
Reusable Manim programmatic template for the Learning Objectives / Roadmap Section.
Adheres strictly to Simplilearn Learning Design & OSL 3.0 Video Guidelines:
- Layout: 40% Left SME Presenter region / 60% Right Structured Content Card
- Typography: Open Sans (Header: SemiBold/Bold #202428; Body: Regular #404040, 34px)
- Visual Style: Clean elevated white card with subtle shadow, rounded corners (10px+)
- Bullet Badges: Vibrant blue circular checkmark badges (#0D6EFD with white tick)
- Editorial Standards: US English, active voice, sentence casing, no duplicate VO
- Timing Control: Per-bullet durations for exact voiceover audio synchronization

Usage:
------
from template2_learning_roadmap import play_learning_roadmap, create_learning_roadmap_mobject

class MyScene(Scene):
    def construct(self):
        play_learning_roadmap(
            self,
            bullets=[
                "Identify basic prompting techniques and appropriate use cases",
                "Apply role-based, conversational, and template-based prompting to analytics scenarios",
                "Compare outputs generated by different prompting techniques for the same task",
            ],
            header_text="By the end of this topic, you will be able to:",
            bullet_durations=[3.0, 3.5, 3.0],  # timing per bullet point
            hold_duration=3.0,
        )

Command-line test render:
-------------------------
py -3.10 -m manim -pql template2_learning_roadmap.py LearningRoadmapScene
"""

